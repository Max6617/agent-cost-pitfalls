/**
 * figures.mjs - the paper's figures, generated from the FILED analysis JSONs.
 *
 * WHY THIS EXISTS. The paper has tables but no charts, and a figure drawn by hand drifts from the
 * table it illustrates. Every number here is read from the shipped analysis JSONs at generation
 * time: no coordinate, label or percentage is written into the .tex by hand. Two runs of this script
 * produce byte-identical files (asserted by tools/figures.test.mjs).
 *
 * SOURCES
 *   analysis/position-adjust-6model-2026-10-09.json   batch-1 adjusted differentials (log and usd)
 *   analysis/position-adjust-batchb-2026-10-09.json   tasks-b adjusted differentials
 *   analysis/ranking-adjusted-2026-10-10.json         A8 tie fractions, raw and position-adjusted
 *   tools/cost-panel.mjs MODELS                       the price cards, hence each model's ratio
 *
 * OUTPUT  paper/figures/*.tex - standalone tikzpicture fragments, no preamble.
 *
 * Usage: node tools/figures.mjs [--out paper/figures] [--root .]
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { MODELS } from './cost-panel.mjs'

export const SOURCES = {
  batch1: 'analysis/position-adjust-6model-2026-10-09.json',
  batchb: 'analysis/position-adjust-batchb-2026-10-09.json',
  ranking: 'analysis/ranking-adjusted-2026-10-10.json',
  aa: 'analysis/aa-placebo-2026-10-10.json',
  // The interleaved A/A of the counterbalanced re-run (notes/plans/RERUN-PLAN.md Q5): the better-measured floor.
  aaInterleaved: 'analysis/rerun-compare-2026-10-11.json',
}

/** Okabe-Ito, the colour-blind-safe palette. */
export const PALETTE = {
  blue: '0072B2',
  orange: 'E69F00',
  green: '009E73',
  vermillion: 'D55E00',
  purple: 'CC79A7',
  sky: '56B4E9',
  grey: '999999',
}

const readJson = (root, p) => JSON.parse(readFileSync(join(root, p), 'utf8'))
const plain = (v, d = 1) => Number(v).toFixed(d)
const signed = (v, d = 1) => (Number(v) >= 0 ? '+' : '') + Number(v).toFixed(d)
const pct = (v, d = 1) => plain(v, d) + '\\%'
/** A signed label for the page: a true minus sign (the width of +), not a hyphen. */
const signedTex = (v, d = 1) => (Number(v) < 0 ? '\\textminus{}' + Math.abs(Number(v)).toFixed(d) : signed(v, d))
/** Tick and axis-label size shared by every figure, so the four read as one set. */
const AXIS_FONTS = '  yticklabel style={font=\\small}, xticklabel style={font=\\small}, xlabel style={font=\\small}, ylabel style={font=\\small},'
const texLabel = (s) => String(s).replace(/[_&%#]/g, (c) => '\\' + c)

/** The ratio a model's price card implies: out / miss, the variable the paper's claim is about. */
export function ratioOf (model) {
  const card = MODELS[model]?.card
  if (!card) return null
  return card.out / card.miss
}

export function loadSources (root = '.') {
  return {
    batch1: readJson(root, SOURCES.batch1),
    batchb: readJson(root, SOURCES.batchb),
    ranking: readJson(root, SOURCES.ranking),
    aa: readJson(root, SOURCES.aa),
    aaInterleaved: readJson(root, SOURCES.aaInterleaved),
  }
}

/** fig 1 - the penalty per model, batch 1, adjusted log, ratio-5.00 members highlighted. */
export function figure1 (src) {
  const models = src.batch1.models
    .map((m) => ({ model: m.model, label: m.label, ratio: ratioOf(m.model), d: m.adjustedLog }))
    .sort((a, b) => a.d.pct - b.d.pct)
  const r5 = models.filter((m) => m.ratio != null && Math.abs(m.ratio - 5) < 1e-9)
  const spanAll = models[models.length - 1].d.pct - models[0].d.pct
  const spanR5 = Math.max(...r5.map((m) => m.d.pct)) - Math.min(...r5.map((m) => m.d.pct))
  const share = (spanR5 / spanAll) * 100
  const top = models.length - 0.4
  const bandLo = Math.min(...r5.map((m) => m.d.pct))
  const bandHi = Math.max(...r5.map((m) => m.d.pct))
  const lo = Math.min(...models.map((m) => m.d.ciLoPct))
  const hi = Math.max(...models.map((m) => m.d.ciHiPct))
  const xmin = Math.floor((lo - 8) / 10) * 10
  const xmax = Math.ceil((hi + 8) / 10) * 10
  const yLabels = models.map((m) => texLabel(m.label) + (Math.abs((m.ratio ?? 0) - 5) < 1e-9 ? ' (ratio 5.00)' : ''))
  const lines = []
  lines.push('% Generated by tools/figures.mjs from ' + SOURCES.batch1 + ' - do not edit by hand.')
  lines.push('\\begin{tikzpicture}')
  lines.push('\\definecolor{f1main}{HTML}{' + PALETTE.blue + '}')
  lines.push('\\definecolor{f1r5}{HTML}{' + PALETTE.vermillion + '}')
  lines.push('\\begin{axis}[')
  lines.push('  width=\\linewidth-6.4cm, height=6.4cm, compat=1.18,')  // room for the model labels and the value labels
  lines.push('  xlabel={PTC vs native, execution-order adjusted on the log scale (\\% of native mean)},')
  lines.push('  xmin=' + xmin + ', xmax=' + xmax + ',')
  lines.push('  ytick={' + models.map((_, i) => i).join(',') + '},')
  lines.push('  yticklabels={' + yLabels.join(',') + '},')
  lines.push(AXIS_FONTS)
  lines.push('  ymin=-0.7, ymax=' + plain(models.length + 0.9, 1) + ',')
  lines.push('  axis y line=left, axis x line=bottom, tick align=outside,')
  lines.push('  grid=major, grid style={gray!18},')
  lines.push('  clip=false,')
  lines.push(']')
  // stops below the bracket so it does not run through the span label
  lines.push('\\draw[gray!55, dashed] (axis cs:0,-0.7) -- (axis cs:0,' + plain(models.length - 0.4, 1) + ');')
  // The ratio-5.00 span, drawn as a bracket between the two extreme ratio-5.00 estimates.
  lines.push('\\draw[f1r5, line width=0.6pt] (axis cs:' + plain(bandLo) + ',' + plain(top + 0.25) + ') -- (axis cs:' + plain(bandLo) + ',' + plain(top + 0.45) + ') -- (axis cs:' + plain(bandHi) + ',' + plain(top + 0.45) + ') -- (axis cs:' + plain(bandHi) + ',' + plain(top + 0.25) + ');')
  lines.push('\\node[font=\\scriptsize, anchor=south, text=f1r5, fill=white, inner sep=1.5pt] at (axis cs:' + plain((bandLo + bandHi) / 2) + ',' + plain(top + 0.5) + ') {ratio-5.00 span: ' + plain(spanR5) + ' of ' + plain(spanAll) + ' points (' + plain(share) + '\\%)};')
  for (let i = 0; i < models.length; i++) {
    const m = models[i]
    const col = Math.abs((m.ratio ?? 0) - 5) < 1e-9 ? 'f1r5' : 'f1main'
    lines.push('\\draw[' + col + ', line width=1.1pt] (axis cs:' + plain(m.d.ciLoPct) + ',' + i + ') -- (axis cs:' + plain(m.d.ciHiPct) + ',' + i + ');')
    lines.push('\\node[circle, fill=' + col + ', inner sep=1.2pt] at (axis cs:' + plain(m.d.pct) + ',' + i + ') {};')
    lines.push('\\node[font=\\scriptsize, anchor=west, text=' + col + '] at (axis cs:' + plain(m.d.ciHiPct) + ',' + i + ') {' + signedTex(m.d.pct) + '\\%};')
  }
  lines.push('\\end{axis}')
  lines.push('\\end{tikzpicture}')
  return { file: 'fig1-penalty-per-model.tex', content: lines.join('\n') + '\n', facts: { models: models.length, spanAll, spanR5, share } }
}

/** fig 2 - the replication: each pre-registered provider's two intervals. */
export function figure2 (src) {
  const PREREG = ['qwen3.8-flash', 'glm-5.3-flash', 'gpt-6-luna', 'deepseek-flash']
  const b1 = new Map(src.batch1.models.map((m) => [m.model, m]))
  const tb = new Map(src.batchb.models.map((m) => [m.model, m]))
  const rows = PREREG.map((model) => {
    const a = b1.get(model), b = tb.get(model)
    if (!a || !b) throw new Error('figure2: missing model ' + model)
    const gap = Math.abs(a.adjustedLog.pct - b.adjustedLog.pct)
    // Disjoint means one interval lies wholly above the other; daylight is the size of the gap.
    const daylight = Math.max(a.adjustedLog.ciLoPct - b.adjustedLog.ciHiPct, b.adjustedLog.ciLoPct - a.adjustedLog.ciHiPct)
    return { model, label: a.label, a: a.adjustedLog, b: b.adjustedLog, gap, daylight, disjoint: daylight > 0 }
  })
  const lo = Math.min(...rows.flatMap((r) => [r.a.ciLoPct, r.b.ciLoPct]))
  const hi = Math.max(...rows.flatMap((r) => [r.a.ciHiPct, r.b.ciHiPct]))
  const xmin = Math.floor((lo - 8) / 10) * 10
  const xmax = Math.ceil((hi + 8) / 10) * 10
  const lines = []
  lines.push('% Generated by tools/figures.mjs from ' + SOURCES.batch1 + ' and ' + SOURCES.batchb + ' - do not edit by hand.')
  lines.push('\\begin{tikzpicture}')
  lines.push('\\definecolor{f2a}{HTML}{' + PALETTE.blue + '}')   // batch 1
  lines.push('\\definecolor{f2b}{HTML}{' + PALETTE.orange + '}') // tasks-b
  lines.push('\\begin{axis}[')
  lines.push('  width=\\linewidth-3.4cm, height=6.0cm, compat=1.18,')  // 3.4cm left for the model labels and notes
  lines.push('  xlabel={PTC vs native, execution-order adjusted on the log scale (\\% of native mean)},')
  lines.push('  xmin=' + xmin + ', xmax=' + xmax + ',')
  lines.push('  ytick={' + rows.map((_, i) => i).join(',') + '},')
  lines.push('  yticklabels={' + rows.map((r) => texLabel(r.label)).join(',') + '},')
  lines.push('  ymin=-0.6, ymax=' + plain(rows.length - 0.4, 2) + ',')
  lines.push('  axis y line=left, axis x line=bottom, tick align=outside,')
  lines.push('  grid=major, grid style={gray!18},')
  lines.push(AXIS_FONTS)
  lines.push('  legend style={at={(0.5,1.03)}, anchor=south, legend columns=2, draw=none, font=\\scriptsize, /tikz/every even column/.append style={column sep=10pt}},')
  lines.push('  clip=false,')
  lines.push(']')
  lines.push('\\addlegendimage{f2a, line width=1.1pt, mark=*, mark size=1.4pt}')
  lines.push('\\addlegendentry{batch 1}')
  lines.push('\\addlegendimage{f2b, line width=1.1pt, mark=*, mark size=1.4pt}')
  lines.push('\\addlegendentry{tasks-b}')
  lines.push('\\draw[gray!55, dashed] (axis cs:0,-0.6) -- (axis cs:0,' + plain(rows.length - 0.4, 2) + ');')
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i]
    const yb = i + 0.17, yt = i - 0.17
    lines.push('\\draw[f2a, line width=1.1pt] (axis cs:' + plain(r.a.ciLoPct) + ',' + plain(yb, 2) + ') -- (axis cs:' + plain(r.a.ciHiPct) + ',' + plain(yb, 2) + ');')
    lines.push('\\node[circle, fill=f2a, inner sep=1.2pt] at (axis cs:' + plain(r.a.pct) + ',' + plain(yb, 2) + ') {};')
    lines.push('\\draw[f2b, line width=1.1pt] (axis cs:' + plain(r.b.ciLoPct) + ',' + plain(yt, 2) + ') -- (axis cs:' + plain(r.b.ciHiPct) + ',' + plain(yt, 2) + ');')
    lines.push('\\node[circle, fill=f2b, inner sep=1.2pt] at (axis cs:' + plain(r.b.pct) + ',' + plain(yt, 2) + ') {};')
    const note = r.disjoint
      ? 'disjoint by ' + plain(r.daylight) + 'pp'
      : (r.model === 'glm-5.3-flash' ? 'agree to ' + plain(r.gap) + 'pp, both null' : 'overlap by ' + plain(-r.daylight) + 'pp')
    lines.push('\\node[font=\\scriptsize, anchor=west] at (axis cs:' + plain(Math.max(r.a.ciHiPct, r.b.ciHiPct) + 2) + ',' + i + ') {' + note + '};')
  }
  lines.push('\\end{axis}')
  lines.push('\\end{tikzpicture}')
  return { file: 'fig2-replication.tex', content: lines.join('\n') + '\n', facts: { rows: rows.length, disjoint: rows.filter((r) => r.disjoint).length, glmGap: rows.find((r) => r.model === 'glm-5.3-flash')?.gap } }
}

