/**
 * The measured A/A floor, as a percentage of per-cell cost.
 *
 * The filed analysis stores dollars and the pass means; the paper reports the interval as a percentage
 * of the first pass's mean ("-5.75% [-15.6%, +3.4%]"), so the conversion happens here rather than in
 * a caption. halfWidthPct = (ciHi - ciLo) / 2 / pass1Mean * 100 - the floor this design resolves.
 */
export function floorFromAA (aa) {
  const names = Object.keys(aa.passes ?? {}).sort()
  if (!names.length) throw new Error('aa-placebo JSON has no passes')
  const base = aa.passes[names[0]].meanBilled
  const b = aa.metrics.billed
  return {
    pass1Mean: base,
    halfWidthPct: ((b.ciHi - b.ciLo) / 2 / base) * 100,
    meanPct: (b.mean / base) * 100,
    ciLoPct: (b.ciLo / base) * 100,
    ciHiPct: (b.ciHi / base) * 100,
    tasks: b.tasks,
  }
}

/**
 * fig 4 - what the floor resolves.
 *
 * The six execution-order-adjusted differentials, with their 95% intervals, against the measured A/A
 * floor, so a reader sees which effects clear it. Each model's RAW point estimate is drawn as a grey
 * diamond because two of the paper's "small effect" statements sit on different bases: GLM's ADJUSTED
 * -8.9% is inside the floor, and Sonnet's RAW +9.5% is, while Sonnet's adjusted +17.0% is not. Both
 * markers are read from the same JSON, and the caption names the basis of each.
 */
export function figure4 (src) {
  const floor = floorFromAA(src.aa)
  const models = src.batch1.models
    .map((m) => ({ model: m.model, label: m.label, d: m.adjustedLog, raw: m.raw }))
    .sort((a, b) => a.d.pct - b.d.pct)
  const n = models.length
  // The two effects PAPER.md reports as sitting at the floor, each on its own basis (adjusted for GLM,
  // raw for Sonnet). Their VALUES come from the JSON; only the selection is editorial.
  const AT_FLOOR = [{ model: 'glm-5.3-flash', basis: 'adjusted' }, { model: 'claude-sonnet-5.5', basis: 'raw' }]
  const floorPct = floor.halfWidthPct
  // The interleaved A/A's half-width, drawn as dashed lines beside the back-to-back band: the re-run
  // measured a WIDER floor, and the reader should see both rather than the flattering one.
  const outerPct = src.aaInterleaved.aa.label.halfWidthPct
  const lo = Math.min(...models.map((m) => Math.min(m.d.ciLoPct, m.raw.pct)), -floorPct, -outerPct)
  const hi = Math.max(...models.map((m) => Math.max(m.d.ciHiPct, m.raw.pct)), floorPct, outerPct)
  const xmin = Math.floor((lo - 8) / 10) * 10
  const xmax = Math.ceil((hi + 8) / 10) * 10
  const inside = models.filter((m) => Math.abs(m.d.pct) <= floorPct).length
  const top = Number((n + 0.8).toFixed(2))
  const lines = []
  lines.push('% Generated by tools/figures.mjs from ' + SOURCES.batch1 + ', ' + SOURCES.aa + ' and ' + SOURCES.aaInterleaved + ' - do not edit by hand.')
  lines.push('\\begin{tikzpicture}')
  lines.push('\\definecolor{f4adj}{HTML}{' + PALETTE.blue + '}')
  lines.push('\\definecolor{f4raw}{HTML}{' + PALETTE.grey + '}')
  lines.push('\\definecolor{f4small}{HTML}{' + PALETTE.vermillion + '}')
  lines.push('\\begin{axis}[')
  lines.push('  width=\\linewidth-5.2cm, height=6.4cm, compat=1.18,')
  lines.push('  xlabel={PTC vs native (\\% of native mean)},')
  lines.push('  xmin=' + xmin + ', xmax=' + xmax + ',')
  lines.push('  ytick={' + models.map((_, i) => i).join(',') + '},')
  lines.push('  yticklabels={' + models.map((m) => texLabel(m.label)).join(',') + '},')
  lines.push('  ymin=-0.7, ymax=' + top + ',')
  lines.push('  axis y line=left, axis x line=bottom, tick align=outside,')
  lines.push('  grid=major, grid style={gray!18},')
  lines.push(AXIS_FONTS)
  lines.push('  legend style={at={(0.5,1.03)}, anchor=south, legend columns=2, draw=none, font=\\scriptsize, legend cell align=left, /tikz/every even column/.append style={column sep=10pt}},')
  lines.push('  clip=false,')
  lines.push(']')
  // The legend is declared first, in reading order (the two estimates, then the two floors), and
  // the plots below use forget plot, so the entries do not follow the drawing order.
  lines.push('\\addlegendimage{only marks, mark=diamond*, mark size=1.5pt, color=f4raw}')
  lines.push('\\addlegendentry{raw}')
  lines.push('\\addlegendimage{only marks, mark=*, mark size=1.4pt, color=f4adj}')
  lines.push('\\addlegendentry{adjusted on the log scale (95\\% CI)}')
  lines.push('\\addlegendimage{area legend, fill=f4raw!25, draw=none}')
  lines.push('\\addlegendentry{back-to-back A/A ($\\pm$' + plain(floorPct) + '\\%)}')
  lines.push('\\addlegendimage{f4small, dashed, line width=0.7pt}')
  lines.push('\\addlegendentry{interleaved A/A ($\\pm$' + plain(outerPct) + '\\%)}')
  lines.push('\\fill[f4raw!25] (axis cs:-' + plain(floorPct) + ',-0.7) rectangle (axis cs:' + plain(floorPct) + ',' + top + ');')
  lines.push('\\draw[f4small, dashed, line width=0.7pt] (axis cs:-' + plain(outerPct) + ',-0.7) -- (axis cs:-' + plain(outerPct) + ',' + top + ');')
  lines.push('\\draw[f4small, dashed, line width=0.7pt] (axis cs:' + plain(outerPct) + ',-0.7) -- (axis cs:' + plain(outerPct) + ',' + top + ');')
  lines.push('\\draw[gray!55, dashed] (axis cs:0,-0.7) -- (axis cs:0,' + top + ');')
  lines.push('\\addplot[forget plot, only marks, mark=diamond*, mark size=1.5pt, color=f4raw] coordinates {' +
    models.map((m, i) => '(' + plain(m.raw.pct) + ',' + i + ')').join(' ') + '};')
  lines.push('\\addplot[forget plot, only marks, mark=*, mark size=1.4pt, color=f4adj] coordinates {' +
    models.map((m, i) => '(' + plain(m.d.pct) + ',' + i + ')').join(' ') + '};')
  for (let i = 0; i < n; i++) {
    const m = models[i]
    lines.push('\\draw[f4adj, line width=1.1pt] (axis cs:' + plain(m.d.ciLoPct) + ',' + i + ') -- (axis cs:' + plain(m.d.ciHiPct) + ',' + i + ');')
    lines.push('\\node[font=\\scriptsize, anchor=west, text=f4adj] at (axis cs:' + plain(m.d.ciHiPct) + ',' + i + ') {' + signedTex(m.d.pct) + '\\%};')
    for (const a of AT_FLOOR) {
      if (a.model === m.model) {
        const x = a.basis === 'adjusted' ? m.d.pct : m.raw.pct
        lines.push('\\node[circle, draw=f4small, line width=0.8pt, inner sep=3.4pt] at (axis cs:' + plain(x) + ',' + i + ') {};')
      }
    }
  }
  lines.push('\\node[font=\\scriptsize, anchor=south east, text=f4small] at (axis cs:' + xmax + ',-0.6) {' + inside + ' of ' + n + ' adjusted estimates inside the floor};')
  lines.push('\\end{axis}')
  lines.push('\\end{tikzpicture}')
  return { file: 'fig4-floor-resolution.tex', content: lines.join('\n') + '\n', facts: { models: n, insideFloor: inside, floorPct: Number(floorPct.toFixed(1)), interleavedPct: Number(outerPct.toFixed(1)) } }
}

export function generate ({ out = 'paper/figures', root = '.', outDir = null } = {}) {
  const src = loadSources(root)
  const figs = [figure1(src), figure2(src), figure3(src), figure4(src)]
  // `root` is where the FILED JSONs live; `outDir` (absolute) lets a test write elsewhere without
  // copying the analysis tree.
  const dest = outDir ?? join(root, out)
  mkdirSync(dest, { recursive: true })
  const written = []
  for (const f of figs) {
    writeFileSync(join(dest, f.file), f.content)
    written.push({ file: join(out, f.file), bytes: Buffer.byteLength(f.content), facts: f.facts })
  }
  return written
}

if (process.argv[1] && process.argv[1].endsWith('figures.mjs')) {
  const argv = process.argv.slice(2)
  const arg = (n, d) => (argv.includes(n) ? argv[argv.indexOf(n) + 1] : d)
  const written = generate({ out: arg('--out', 'paper/figures'), root: arg('--root', '.') })
  for (const w of written) console.log('  ' + w.file + '  ' + w.bytes + ' bytes  ' + JSON.stringify(w.facts))
  console.log('wrote ' + written.length + ' figure(s)')
}
